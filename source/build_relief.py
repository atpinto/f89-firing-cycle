# Builds the F89 outer-body relief (texture + depth map) from the right-side photo.
# Run from the project root:  python3 source/build_relief.py
import io, base64, numpy as np
from PIL import Image, ImageFilter

SRC = 'reference-photos/minimi-right-side.jpg'
TILT = -8.53                 # degrees: levels the barrel
S = 0.0535                   # cm per px of the levelled, cropped photo (butt to muzzle = 104 cm)
BREECH_PX, AXIS_PY = 1010, 225
ZMAX = 2.6                   # cm of half-thickness encoded as depth 255
DEPTH_W = 900                # width of the depth grid (the texture stays at full resolution)

im = Image.open(SRC).convert('RGB').rotate(TILT, resample=Image.BICUBIC, expand=True, fillcolor=(255, 255, 255))
a = np.asarray(im).astype(int)
def backdrop(a): return (a.min(2) > 232) & (a.max(2) - a.min(2) < 14)
ys, xs = np.nonzero(~backdrop(a))
im = im.crop((xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5))
a = np.asarray(im).astype(int); H, W = a.shape[:2]
ys, xs = np.mgrid[0:H, 0:W]
def box(x0, x1, y0, y1): return (xs >= x0) & (xs < x1) & (ys >= y0) & (ys < y1)
def erode(m):
    e = m.copy(); e[1:] &= m[:-1]; e[:-1] &= m[1:]; e[:, 1:] &= m[:, :-1]; e[:, :-1] &= m[:, 1:]; return e
def dist(m, n=16):
    d = np.zeros(m.shape, float); cur = m.copy()
    for _ in range(n): d += cur; cur = erode(cur)
    return d

gun = erode(~backdrop(a))
gun &= ~(box(1330, W, 338, H))            # bipod legs: modelled in 3D instead
gun &= ~(box(706, 796, 350, 414))         # trigger blade: animated in 3D
gun = erode(gun)

# half-thickness (cm) by region, rounded off towards the outline
# Half-widths of the main body come from the top-down view (reference-photos/minimi-views-top.jpg, 0.133 cm/px):
# handguard and feed cover 5.0 cm across, receiver behind the grip 4.7, butt 4.1 (butt plate 4.9), rail 2.1.
# The top view cannot separate parts stacked vertically (grip, guard, handle), so those stay estimates.
base = np.full((H, W), 2.3)
base[box(0, 445, 0, H)] = 2.05            # butt
base[box(0, 45, 0, H)] = 2.45             # butt plate
base[box(440, 1000, 190, 346)] = 2.35     # receiver
base[box(800, 1000, 190, 346)] = 2.5      # receiver over the belt feed
base[box(480, 1000, 100, 190)] = 2.5      # feed cover
base[box(600, 975, 100, 142)] = 1.05      # rail on the feed cover
base[box(495, 610, 90, 160)] = 1.6        # rear sight
base[box(525, 705, 346, 570)] = 1.3       # pistol grip
base[box(700, 815, 346, 435)] = 0.5       # trigger guard
base[box(985, 1400, 195, 370)] = 2.5      # handguard
base[box(985, 1200, 0, 195)] = 0.6        # carrying handle
base[box(985, 1190, 0, 100)] = 0.9
base[box(1400, W, 195, 250)] = 0.9        # barrel
base[box(1380, 1475, 240, 336)] = 1.4     # bipod yoke
base[box(1475, 1537, 195, 305)] = 1.35    # gas block
base[box(1500, 1565, 0, 195)] = 0.3       # foresight
base[box(1537, 1615, 250, 320)] = 0.9     # gas regulator
b = np.asarray(Image.fromarray((base * 90).astype(np.uint8)).filter(ImageFilter.BoxBlur(5))).astype(float) / 90
R = np.minimum(0.6, b * 0.55)
k = np.clip(dist(gun) * S / R, 0, 1)
h = np.where(gun, b * np.sqrt(1 - (1 - k) ** 2), 0)

# depth map on a coarser grid; 0 = no body
DEPTH_H = round(H * DEPTH_W / W)
cover = np.asarray(Image.fromarray((gun * 255).astype(np.uint8)).resize((DEPTH_W, DEPTH_H), Image.BOX))
hd = np.asarray(Image.fromarray(h.astype(np.float32)).resize((DEPTH_W, DEPTH_H), Image.BOX))
depth = np.where(cover > 110, np.clip(np.round(hd / ZMAX * 254) + 1, 1, 255), 0).astype(np.uint8)
Image.fromarray(depth).save('reference-photos/minimi-right-side-depth.png', optimize=True)

# texture: bleed body colours outwards so the edges never pick up the white backdrop
t = a.astype(float); m = gun.copy()
for _ in range(10):
    acc = np.zeros_like(t); cnt = np.zeros(m.shape)
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        sm = np.roll(m, (dy, dx), (0, 1)); acc += np.roll(t, (dy, dx), (0, 1)) * sm[..., None]; cnt += sm
    grow = ~m & (cnt > 0); t[grow] = acc[grow] / cnt[grow][:, None]; m |= grow
t[~m] = 40
Image.fromarray(t.astype(np.uint8)).save('reference-photos/minimi-right-side-texture.jpg', quality=86)

def uri(path, mime): return f'data:{mime};base64,' + base64.b64encode(open(path, 'rb').read()).decode()
open('f89-assets.js', 'w').write(
    '// Generated by source/build_relief.py from reference-photos/ (embedded so the page also works when opened from disk).\n'
    'window.F89_ASSETS = {\n'
    f'  tex: "{uri("reference-photos/minimi-right-side-texture.jpg", "image/jpeg")}",\n'
    f'  depth: "{uri("reference-photos/minimi-right-side-depth.png", "image/png")}",\n'
    f'  W: {DEPTH_W}, H: {DEPTH_H}, cm: {S * W / DEPTH_W:.6f}, zMax: {ZMAX}, breechPx: {BREECH_PX * DEPTH_W / W:.3f}, axisPx: {AXIS_PY * DEPTH_W / W:.3f}\n'
    '};\n')
print('photo', (W, H), 'depth', (DEPTH_W, DEPTH_H), 'body px', int((depth > 0).sum()))
